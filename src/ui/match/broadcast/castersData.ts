// The caster desk: a roster of five broadcast personalities (their real handles; this is a non-commercial fan game) and
// the line pools the commentary engine (commentary.ts) fills in. Every line stays in the caster's professional on-air
// persona and only talks about the match: no personal facts, no opinions about real people beyond the game.
//
// Pools are keyed by category. English casters read their own pool first and fall back to the shared English pool;
// Hoàng Luân casts in Vietnamese: his lines are [Vietnamese, English gloss] pairs with the same placeholders.
// Placeholders are filled by fans.fill() ({UPPER} = caps); a line whose placeholder has no value is skipped.
//
// Common placeholders: {team} {oteam} (subject's team / the other team, short names), {tname} (full name), {p} {pc}
// (player, champion), {v} {vc} (victim), {mins} {time}, {partner} (the other caster), {comp}, {seriesline}, {lead}
// {leader} {trailer}, {lane}/{lanevi}, {drake}/{drakevi}, {obj}/{objvi}, {tier}/{tiervi}. See commentary.ts for the
// full list per category.

